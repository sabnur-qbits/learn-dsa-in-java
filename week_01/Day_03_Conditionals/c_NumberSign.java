public class c_NumberSign{ 
    public static void main(String[] args){
        int num;
        num = 0;
        if(num == 0){
            System.out.println("The number is exactly Zero.");
        }
        else if(num > 0){
            System.out.println("The number is Positive.");
        }
        else{
            System.out.println("The number is Negetive.");
        }
    }
}