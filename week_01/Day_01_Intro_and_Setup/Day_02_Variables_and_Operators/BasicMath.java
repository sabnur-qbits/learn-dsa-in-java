public class BasicMath{
    public static void main(String[] args){
        int a = 10;
        int b = 5;
        int add = a+b;
        int sub = a-b;
        int mul = a*b;
        int mod = a%b;
        System.out.println("Addition: " + add);
        System.out.println("Substraction: " + sub);
        System.out.println("Multiplication:" + mul);
        System.out.println("Remainder: " + mod);
    }
}