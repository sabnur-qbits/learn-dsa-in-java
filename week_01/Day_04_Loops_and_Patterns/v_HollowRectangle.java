public class v_HollowRectangle{
    public static void main(String[] args){
        for(int i=1;i<=4;i++){
                for(int n=1;n<=5;n++){
                    if(i==1 || i==4 || n==1 || n==5){
                        System.out.print("*");
                    }
                    else{
                    System.out.print(" ");
                    }  
                    
                }
                System.out.println();
            }
            
        }
     }